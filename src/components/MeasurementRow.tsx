import { Badge } from "./Badge";
import { describeMeasurement, formatRelative } from "@/utils/format";
import { MEASUREMENT_LABEL } from "@/utils/labels";
import type { Measurement } from "@/types";

export function MeasurementRow({ m, now }: { m: Measurement; now: Date }) {
  const available = m.value.state === "available";
  return (
    <li className="flex items-start justify-between gap-4 border-b border-zinc-800 py-2.5 last:border-0" data-testid={`m-${m.id}`}>
      <div className="min-w-0">
        <div className="text-sm text-zinc-200">
          {MEASUREMENT_LABEL[m.id]}
          {m.scope && <span className="ml-2 font-mono text-xs text-zinc-500">{m.scope}</span>}
        </div>
        <div className="mt-1 flex flex-wrap gap-1">
          {m.simulated && <Badge tone="warn" title="Generated by a simulator. Not real usage.">Simulated</Badge>}
          {m.estimated && <Badge tone="info" title="Computed locally at list price; not a bill.">Estimate</Badge>}
          {m.stale && <Badge tone="warn" title="Last known value; could not be refreshed or is old.">Stale</Badge>}
          {m.restored && <Badge title="Loaded from saved history; not observed in this run.">From history</Badge>}
          {m.sourceAt && available && <span className="text-[11px] text-zinc-500">reported {formatRelative(m.sourceAt, now)}</span>}
        </div>
      </div>
      <div className="text-right">
        <div className={available ? "text-lg font-semibold tabular-nums" : "text-sm italic text-zinc-500"} data-testid={`v-${m.id}`}>
          {describeMeasurement(m)}
        </div>
        {available && m.resetsAt && <div className="text-[11px] text-zinc-500">resets {formatRelative(m.resetsAt, now)}</div>}
      </div>
    </li>
  );
}
